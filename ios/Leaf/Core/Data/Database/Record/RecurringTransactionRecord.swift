import Foundation
import GRDB

public struct RecurringTransactionRecord: Codable, FetchableRecord, MutablePersistableRecord, TableRecord, Sendable {
    public static let databaseTableName = "recurring_transactions"

    public var id: Int64?
    public var title: String
    public var amountSubunits: Int64
    public var type: String
    public var categoryId: Int64
    public var paymentMethod: String
    public var note: String?
    public var frequency: String
    public var dayOfMonth: Int
    public var dayOfWeek: Int
    public var startDate: Int64
    public var endDate: Int64?
    public var isEnabled: Bool
    public var isAutoGenerated: Bool
    public var reminderDaysBefore: Int?
    public var lastGeneratedDate: Int64?
    public var status: String
    public var recurrenceInterval: Int
    public var isSubscription: Bool
    public var createdAt: Int64
    public var updatedAt: Int64

    enum CodingKeys: String, CodingKey {
        case id
        case title
        case amountSubunits = "amount_subunits"
        case type
        case categoryId = "category_id"
        case paymentMethod = "payment_method"
        case note
        case frequency
        case dayOfMonth = "day_of_month"
        case dayOfWeek = "day_of_week"
        case startDate = "start_date"
        case endDate = "end_date"
        case isEnabled = "is_enabled"
        case isAutoGenerated = "is_auto_generated"
        case reminderDaysBefore = "reminder_days_before"
        case lastGeneratedDate = "last_generated_date"
        case status
        case recurrenceInterval = "recurrence_interval"
        case isSubscription = "is_subscription"
        case createdAt = "created_at"
        case updatedAt = "updated_at"
    }

    public init(
        id: Int64? = nil,
        title: String,
        amountSubunits: Int64,
        type: String,
        categoryId: Int64,
        paymentMethod: String = "CASH",
        note: String? = nil,
        frequency: String = "MONTHLY",
        dayOfMonth: Int = 1,
        dayOfWeek: Int = 1,
        startDate: Int64 = Int64(Date().timeIntervalSince1970 * 1000),
        endDate: Int64? = nil,
        isEnabled: Bool = true,
        isAutoGenerated: Bool = false,
        reminderDaysBefore: Int? = 1,
        lastGeneratedDate: Int64? = nil,
        status: String = "ACTIVE",
        recurrenceInterval: Int = 1,
        isSubscription: Bool = false,
        createdAt: Int64 = Int64(Date().timeIntervalSince1970 * 1000),
        updatedAt: Int64 = Int64(Date().timeIntervalSince1970 * 1000)
    ) {
        self.id = id
        self.title = title
        self.amountSubunits = amountSubunits
        self.type = type
        self.categoryId = categoryId
        self.paymentMethod = paymentMethod
        self.note = note
        self.frequency = frequency
        self.dayOfMonth = dayOfMonth
        self.dayOfWeek = dayOfWeek
        self.startDate = startDate
        self.endDate = endDate
        self.isEnabled = isEnabled
        self.isAutoGenerated = isAutoGenerated
        self.reminderDaysBefore = reminderDaysBefore
        self.lastGeneratedDate = lastGeneratedDate
        self.status = status
        self.recurrenceInterval = recurrenceInterval
        self.isSubscription = isSubscription
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }

    public mutating func didInsert(_ inserted: InsertionSuccess) {
        id = inserted.rowID
    }
}

