    public func markOccurrenceAsPaid(
        occurrenceId: Int64,
        paymentMethod: PaymentMethod,
        paidAt: Int64
    ) async throws -> Int64 {
        try await database.writer.write { db in
            // 1. Fetch occurrence and schedule
            guard let row = try Row.fetchOne(db, sql: """
                SELECT o.*, r.title as rec_title, r.type as rec_type, r.category_id as rec_cat_id, r.note as rec_note
                FROM recurring_transaction_occurrences o
                JOIN recurring_transactions r ON o.recurring_transaction_id = r.id
                WHERE o.id = ?
            """, arguments: [occurrenceId]) else {
                throw NSError(domain: "Leaf.Recurring", code: 404, userInfo: [NSLocalizedDescriptionKey: "Occurrence not found"])
            }

            // If already linked to a transaction, return existing transaction ID
            if let existingTxId = row["transaction_id"] as Int64?, existingTxId > 0 {
                return existingTxId
            }

            let amountSubunits: Int64 = row["amount_subunits"]
            let type: String = row["rec_type"]
            let categoryId: Int64 = row["rec_cat_id"]
            let title: String = row["rec_title"]
            let note: String? = row["rec_note"]
            let recurringId: Int64 = row["recurring_transaction_id"]
            let now = Int64(Date().timeIntervalSince1970 * 1000)

            // 2. Insert into transactions table
            let txNote = (note != nil && !note!.isEmpty) ? note : "Recurring: \(title)"
            var txRecord = TransactionRecord(
                amountSubunits: amountSubunits,
                type: type,
                categoryId: categoryId,
                paymentMethod: paymentMethod.rawValue,
                note: txNote,
                timestamp: paidAt,
                createdAt: now,
                updatedAt: now,
                isInternalTransfer: false,
                recurringTransactionId: recurringId
            )
            try txRecord.insert(db)
            let createdTxId = txRecord.id ?? 0

            // 3. Update occurrence record to PAID and link transaction
            try db.execute(
                sql: """
                UPDATE recurring_transaction_occurrences
                SET status = 'PAID', transaction_id = ?, paid_at = ?, updated_at = ?
                WHERE id = ?
                """,
                arguments: [createdTxId, paidAt, now, occurrenceId]
            )

            // 4. Update lastGeneratedDate on recurring schedule
            try db.execute(
                sql: "UPDATE recurring_transactions SET last_generated_date = ?, updated_at = ? WHERE id = ?",
                arguments: [paidAt, now, recurringId]
            )

            return createdTxId
        }
    }

    public func reversePaidOccurrence(occurrenceId: Int64) async throws {
        try await database.writer.write { db in
            guard let row = try Row.fetchOne(db, sql: """
                SELECT id, scheduled_date, transaction_id, status
                FROM recurring_transaction_occurrences
                WHERE id = ?
            """, arguments: [occurrenceId]) else {
                throw NSError(domain: "Leaf.Recurring", code: 404, userInfo: [NSLocalizedDescriptionKey: "Occurrence not found"])
            }

            let txId: Int64? = row["transaction_id"]
            let scheduledDate: Int64 = row["scheduled_date"]

            // 1. Delete associated transaction from ledger if present
            if let txId = txId {
                _ = try TransactionRecord.deleteOne(db, key: txId)
            }

            // 2. Re-resolve occurrence status according to local calendar date
            let resolved = RecurrenceEngine.resolveStatus(
                scheduledDateEpoch: scheduledDate,
                isPaid: false,
                isSkipped: false
            )
            let now = Int64(Date().timeIntervalSince1970 * 1000)

            // 3. Atomically reset occurrence to unpaid state
            try db.execute(
                sql: """
                UPDATE recurring_transaction_occurrences
                SET status = ?, transaction_id = NULL, paid_at = NULL, updated_at = ?
                WHERE id = ?
                """,
                arguments: [resolved.rawValue, now, occurrenceId]
            )
        }
    }

    public func reconcilePendingOccurrencesStatuses(referenceDate: Date = Date()) async throws {
        try await database.writer.write { db in
            var cal = Calendar(identifier: .gregorian)
            cal.timeZone = TimeZone.current
            let todayStart = cal.startOfDay(for: referenceDate)
            guard let tomorrowStart = cal.date(byAdding: .day, value: 1, to: todayStart) else { return }

            let todayStartEpoch = Int64(todayStart.timeIntervalSince1970 * 1000)
            let tomorrowStartEpoch = Int64(tomorrowStart.timeIntervalSince1970 * 1000)
            let now = Int64(Date().timeIntervalSince1970 * 1000)

            // 1. Mark past unpaid as OVERDUE
            try db.execute(
                sql: """
                UPDATE recurring_transaction_occurrences
                SET status = 'OVERDUE', updated_at = ?
                WHERE status NOT IN ('PAID', 'SKIPPED')
                  AND scheduled_date < ?
                """,
                arguments: [now, todayStartEpoch]
            )

            // 2. Mark today's unpaid as DUE
            try db.execute(
                sql: """
                UPDATE recurring_transaction_occurrences
                SET status = 'DUE', updated_at = ?
                WHERE status NOT IN ('PAID', 'SKIPPED')
                  AND scheduled_date >= ?
                  AND scheduled_date < ?
                """,
                arguments: [now, todayStartEpoch, tomorrowStartEpoch]
            )

            // 3. Mark future unpaid as UPCOMING
            try db.execute(
                sql: """
                UPDATE recurring_transaction_occurrences
                SET status = 'UPCOMING', updated_at = ?
                WHERE status NOT IN ('PAID', 'SKIPPED')
                  AND scheduled_date >= ?
                """,
                arguments: [now, tomorrowStartEpoch]
            )
        }
    }

    public func reconcileFutureOccurrences(
        forRecurringId recurringId: Int64,
        updateUpcomingDueOccurrence: Bool,
        newSchedule: RecurringTransaction
    ) async throws -> [Int64] {
        try await database.writer.write { db in
            var cal = Calendar(identifier: .gregorian)
            cal.timeZone = TimeZone.current
            let todayStart = cal.startOfDay(for: Date())
            let tomorrowStart = cal.date(byAdding: .day, value: 1, to: todayStart) ?? Date()
            let tomorrowStartEpoch = Int64(tomorrowStart.timeIntervalSince1970 * 1000)

            let rows: [Row]
            if updateUpcomingDueOccurrence {
                // Remove all unpaid occurrences (including upcoming/due)
                rows = try Row.fetchAll(db, sql: """
                    SELECT id FROM recurring_transaction_occurrences
                    WHERE recurring_transaction_id = ?
                      AND status NOT IN ('PAID', 'SKIPPED')
                """, arguments: [recurringId])

                try db.execute(sql: """
                    DELETE FROM recurring_transaction_occurrences
                    WHERE recurring_transaction_id = ?
                      AND status NOT IN ('PAID', 'SKIPPED')
                """, arguments: [recurringId])
            } else {
                // Remove only strictly future occurrences, preserving the current due/overdue occurrence
                rows = try Row.fetchAll(db, sql: """
                    SELECT id FROM recurring_transaction_occurrences
                    WHERE recurring_transaction_id = ?
                      AND status NOT IN ('PAID', 'SKIPPED')
                      AND scheduled_date >= ?
                """, arguments: [recurringId, tomorrowStartEpoch])

                try db.execute(sql: """
                    DELETE FROM recurring_transaction_occurrences
                    WHERE recurring_transaction_id = ?
                      AND status NOT IN ('PAID', 'SKIPPED')
                      AND scheduled_date >= ?
                """, arguments: [recurringId, tomorrowStartEpoch])
            }

            return rows.compactMap { $0["id"] as Int64? }
        }
    }

