    // MARK: - Row Mapping Helpers

    private static func rowToRecurringTransaction(_ row: Row) -> RecurringTransaction {
        let category: Category?
        if let catId = row["category_id"] as Int64?, let catName = row["cat_name"] as String? {
            category = Category(
                id: catId,
                name: catName,
                iconName: row["cat_icon"] as String? ?? "category",
                colorHex: row["cat_color"] as String? ?? "#10B981",
                type: TransactionType(rawValue: row["cat_type"] as String? ?? "EXPENSE") ?? .expense,
                isDefault: (row["cat_is_default"] as Int? ?? 0) == 1
            )
        } else {
            category = nil
        }

        let freqRaw = row["frequency"] as String? ?? "MONTHLY"
        let statusRaw = row["status"] as String? ?? "ACTIVE"
        let typeRaw = row["type"] as String? ?? "EXPENSE"
        let paymentMethodRaw = row["payment_method"] as String? ?? "CASH"

        let frequency = RecurringScheduleFrequency(rawValue: freqRaw) ?? .monthly
        let status = RecurringScheduleStatus(rawValue: statusRaw) ?? .active
        let type = TransactionType(rawValue: typeRaw) ?? .expense
        let paymentMethod = PaymentMethod.fromString(paymentMethodRaw)

        let startDate = row["start_date"] as Int64? ?? Int64(Date().timeIntervalSince1970 * 1000)
        let endDate = row["end_date"] as Int64?
        let anchorDay = row["day_of_month"] as Int? ?? 1
        let anchorWeek = row["day_of_week"] as Int? ?? 1
        let interval = row["recurrence_interval"] as Int? ?? 1

        let nextOcc = RecurrenceEngine.calculateNextOccurrence(
            startDateEpoch: startDate,
            endDateEpoch: endDate,
            frequency: frequency,
            interval: interval,
            anchorDayOfMonth: anchorDay,
            anchorDayOfWeek: anchorWeek
        )

        return RecurringTransaction(
            id: row["id"],
            title: row["title"],
            amount: Amount(subunits: row["amount_subunits"]),
            type: type,
            categoryId: row["category_id"],
            category: category,
            paymentMethod: paymentMethod,
            note: row["note"],
            frequency: frequency,
            recurrenceInterval: interval,
            dayOfMonth: anchorDay,
            dayOfWeek: anchorWeek,
            startDate: startDate,
            endDate: endDate,
            status: status,
            isAutoGenerated: (row["is_auto_generated"] as Int? ?? 0) == 1,
            reminderDaysBefore: row["reminder_days_before"],
            isSubscription: (row["is_subscription"] as Int? ?? 0) == 1,
            lastGeneratedDate: row["last_generated_date"],
            nextOccurrenceDate: nextOcc,
            createdAt: row["created_at"],
            updatedAt: row["updated_at"]
        )
    }

    private static func rowToOccurrence(_ row: Row) -> RecurringTransactionOccurrence {
        let category: Category?
        if let catId = row["rec_cat_id"] as Int64?, let catName = row["cat_name"] as String? {
            category = Category(
                id: catId,
                name: catName,
                iconName: row["cat_icon"] as String? ?? "category",
                colorHex: row["cat_color"] as String? ?? "#10B981",
                type: TransactionType(rawValue: row["cat_type"] as String? ?? "EXPENSE") ?? .expense,
                isDefault: (row["cat_is_default"] as Int? ?? 0) == 1
            )
        } else {
            category = nil
        }

        let parentSummary = RecurringTransaction(
            id: row["recurring_transaction_id"],
            title: row["rec_title"] as String? ?? "Payment",
            amount: Amount(subunits: row["amount_subunits"]),
            type: TransactionType(rawValue: row["rec_type"] as String? ?? "EXPENSE") ?? .expense,
            categoryId: row["rec_cat_id"] as Int64? ?? 0,
            category: category,
            paymentMethod: PaymentMethod.fromString(row["rec_payment_method"] as String?),
            isSubscription: (row["rec_is_sub"] as Int? ?? 0) == 1
        )

        let statusRaw = row["status"] as String? ?? "UPCOMING"
        let scheduledDate = row["scheduled_date"] as Int64
        let isPaid = statusRaw == "PAID"
        let isSkipped = statusRaw == "SKIPPED"

        let resolvedStatus: BillPaymentStatus
        if isPaid {
            resolvedStatus = .paid
        } else if isSkipped {
            resolvedStatus = .skipped
        } else {
            resolvedStatus = RecurrenceEngine.resolveStatus(
                scheduledDateEpoch: scheduledDate,
                isPaid: false,
                isSkipped: false
            )
        }

        return RecurringTransactionOccurrence(
            id: row["id"],
            recurringTransactionId: row["recurring_transaction_id"],
            recurringTransaction: parentSummary,
            scheduledDate: scheduledDate,
            dueDate: row["due_date"],
            amount: Amount(subunits: row["amount_subunits"]),
            status: resolvedStatus,
            transactionId: row["transaction_id"],
            paidAt: row["paid_at"],
            snoozedUntil: row["snoozed_until"],
            createdAt: row["created_at"],
            updatedAt: row["updated_at"]
        )
    }
