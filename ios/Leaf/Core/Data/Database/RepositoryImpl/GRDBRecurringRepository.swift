    // MARK: - Occurrence Ledger

    public func getOccurrences(forRecurringId recurringId: Int64) async throws -> [RecurringTransactionOccurrence] {
        try await database.writer.read { db in
            let rows = try Row.fetchAll(db, sql: """
                SELECT o.*,
                       r.title as rec_title, r.type as rec_type, r.payment_method as rec_payment_method,
                       r.is_subscription as rec_is_sub, r.category_id as rec_cat_id,
                       c.name as cat_name, c.icon_name as cat_icon, c.color_hex as cat_color, c.type as cat_type, c.is_default as cat_is_default
                FROM recurring_transaction_occurrences o
                JOIN recurring_transactions r ON o.recurring_transaction_id = r.id
                LEFT JOIN categories c ON r.category_id = c.id
                WHERE o.recurring_transaction_id = ?
                ORDER BY o.scheduled_date DESC
            """, arguments: [recurringId])

            return rows.map { Self.rowToOccurrence($0) }
        }
    }

    public func getUpcomingBills(limit: Int?) async throws -> [RecurringTransactionOccurrence] {
        try await database.writer.read { db in
            var sql = """
                SELECT o.*,
                       r.title as rec_title, r.type as rec_type, r.payment_method as rec_payment_method,
                       r.is_subscription as rec_is_sub, r.category_id as rec_cat_id,
                       c.name as cat_name, c.icon_name as cat_icon, c.color_hex as cat_color, c.type as cat_type, c.is_default as cat_is_default
                FROM recurring_transaction_occurrences o
                JOIN recurring_transactions r ON o.recurring_transaction_id = r.id
                LEFT JOIN categories c ON r.category_id = c.id
                WHERE r.status != 'CANCELLED'
                ORDER BY CASE
                    WHEN o.status = 'OVERDUE' THEN 1
                    WHEN o.status = 'DUE' THEN 2
                    WHEN o.status = 'UPCOMING' THEN 3
                    WHEN o.status = 'PAID' THEN 4
                    ELSE 5
                END, o.due_date ASC
            """
            if let limit = limit {
                sql += " LIMIT \(limit)"
            }

            let rows = try Row.fetchAll(db, sql: sql)
            return rows.map { Self.rowToOccurrence($0) }
        }
    }

