import Foundation

/// Domain model representing a scheduled recurring financial activity (expense, income, subscription, or bill).
public struct RecurringTransaction: Identifiable, Hashable, Codable, Sendable {
    public let id: Int64
    public let title: String
    public let amount: Amount
    public let type: TransactionType
    public let categoryId: Int64
    public let category: Category?
    public let paymentMethod: PaymentMethod
    public let note: String?
    public let frequency: RecurringScheduleFrequency
    public let recurrenceInterval: Int
    public let dayOfMonth: Int
    public let dayOfWeek: Int
    public let startDate: Int64
    public let endDate: Int64?
    public let status: RecurringScheduleStatus
    public let isAutoGenerated: Bool
    public let reminderDaysBefore: Int?
    public let isSubscription: Bool
    public let lastGeneratedDate: Int64?
    public let nextOccurrenceDate: Int64?
    public let createdAt: Int64
    public let updatedAt: Int64

    public init(
        id: Int64 = 0,
        title: String,
        amount: Amount,
        type: TransactionType,
        categoryId: Int64,
        category: Category? = nil,
        paymentMethod: PaymentMethod = .cash,
        note: String? = nil,
        frequency: RecurringScheduleFrequency = .monthly,
        recurrenceInterval: Int = 1,
        dayOfMonth: Int = 1,
        dayOfWeek: Int = 1,
        startDate: Int64 = Int64(Date().timeIntervalSince1970 * 1000),
        endDate: Int64? = nil,
        status: RecurringScheduleStatus = .active,
        isAutoGenerated: Bool = false,
        reminderDaysBefore: Int? = 1,
        isSubscription: Bool = false,
        lastGeneratedDate: Int64? = nil,
        nextOccurrenceDate: Int64? = nil,
        createdAt: Int64 = Int64(Date().timeIntervalSince1970 * 1000),
        updatedAt: Int64 = Int64(Date().timeIntervalSince1970 * 1000)
    ) {
        self.id = id
        self.title = title
        self.amount = amount
        self.type = type
        self.categoryId = categoryId
        self.category = category
        self.paymentMethod = paymentMethod
        self.note = note
        self.frequency = frequency
        self.recurrenceInterval = recurrenceInterval
        self.dayOfMonth = dayOfMonth
        self.dayOfWeek = dayOfWeek
        self.startDate = startDate
        self.endDate = endDate
        self.status = status
        self.isAutoGenerated = isAutoGenerated
        self.reminderDaysBefore = reminderDaysBefore
        self.isSubscription = isSubscription
        self.lastGeneratedDate = lastGeneratedDate
        self.nextOccurrenceDate = nextOccurrenceDate
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }

    /// Monthly estimated monetary cost for budgeting and subscription overhead projection.
    public var estimatedMonthlyAmount: Amount {
        let rawSubunits = Double(amount.subunits) * frequency.monthlyMultiplier / Double(max(1, recurrenceInterval))
        return Amount(subunits: Int64(round(rawSubunits)))
    }

    /// Annual estimated monetary cost.
    public var estimatedAnnualAmount: Amount {
        let monthly = estimatedMonthlyAmount
        return Amount(subunits: monthly.subunits * 12)
    }

    /// Whether this schedule is actively generating/tracking occurrences.
    public var isActive: Bool {
        status == .active
    }
}

