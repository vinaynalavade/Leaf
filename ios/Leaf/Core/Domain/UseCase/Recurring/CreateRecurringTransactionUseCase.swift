import Foundation

public final class CreateRecurringTransactionUseCase: Sendable {
    private let recurringRepository: RecurringRepositoryProtocol
    private let notificationService: NotificationService

    public init(
        recurringRepository: RecurringRepositoryProtocol,
        notificationService: NotificationService = .shared
    ) {
        self.recurringRepository = recurringRepository
        self.notificationService = notificationService
    }

    public func execute(
        title: String,
        amount: Amount,
        type: TransactionType,
        categoryId: Int64,
        paymentMethod: PaymentMethod = .cash,
        note: String? = nil,
        frequency: RecurringScheduleFrequency = .monthly,
        recurrenceInterval: Int = 1,
        dayOfMonth: Int = 1,
        dayOfWeek: Int = 1,
        startDate: Int64 = Int64(Date().timeIntervalSince1970 * 1000),
        endDate: Int64? = nil,
        isAutoGenerated: Bool = false,
        reminderDaysBefore: Int? = 1,
        isSubscription: Bool = false
    ) async throws -> Int64 {
        let schedule = RecurringTransaction(
            title: title.trimmingCharacters(in: .whitespacesAndNewlines),
            amount: amount,
            type: type,
            categoryId: categoryId,
            paymentMethod: paymentMethod,
            note: note?.trimmingCharacters(in: .whitespacesAndNewlines),
            frequency: frequency,
            recurrenceInterval: max(1, recurrenceInterval),
            dayOfMonth: min(max(1, dayOfMonth), 31),
            dayOfWeek: min(max(1, dayOfWeek), 7),
            startDate: startDate,
            endDate: endDate,
            status: .active,
            isAutoGenerated: isAutoGenerated,
            reminderDaysBefore: reminderDaysBefore,
            isSubscription: isSubscription
        )

        let createdId = try await recurringRepository.insertRecurringTransaction(schedule)

        // Seed initial occurrences up to next 60 days
        let horizonDate = Calendar.current.date(byAdding: .day, value: 60, to: Date()) ?? Date()
        let timestamps = RecurrenceEngine.generateOccurrenceTimestamps(
            startDateEpoch: startDate,
            endDateEpoch: endDate,
            frequency: frequency,
            interval: recurrenceInterval,
            anchorDayOfMonth: dayOfMonth,
            anchorDayOfWeek: dayOfWeek,
            upTo: horizonDate
        )

        for ts in timestamps {
            let initialStatus = RecurrenceEngine.resolveStatus(
                scheduledDateEpoch: ts,
                isPaid: false,
                isSkipped: false
            )
            let occ = RecurringTransactionOccurrence(
                recurringTransactionId: createdId,
                scheduledDate: ts,
                dueDate: ts,
                amount: amount,
                status: initialStatus
            )
            if let occId = try await recurringRepository.insertOccurrenceIfNotExists(occ) {
                if let days = reminderDaysBefore {
                    let dueDate = Date(timeIntervalSince1970: Double(ts) / 1000.0)
                    await notificationService.scheduleBillReminder(
                        occurrenceId: occId,
                        title: title,
                        amountFormatted: amount.formatted(),
                        dueDate: dueDate,
                        reminderDaysBefore: days
                    )
                }
            }
        }

        return createdId
    }
}

