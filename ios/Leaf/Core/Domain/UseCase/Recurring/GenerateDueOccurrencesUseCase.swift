import Foundation

/// Generation system that evaluates all active recurring schedules, records missed and upcoming occurrences
/// across a 90-day horizon, synchronizes local calendar statuses (OVERDUE, DUE, UPCOMING), and
/// creates financial ledger transactions for explicitly configured auto-record schedules.
public final class GenerateDueOccurrencesUseCase: Sendable {
    private let recurringRepository: RecurringRepositoryProtocol
    private let notificationService: NotificationService
    private let preferencesRepository: UserPreferencesRepositoryProtocol?

    public init(
        recurringRepository: RecurringRepositoryProtocol,
        notificationService: NotificationService = .shared,
        preferencesRepository: UserPreferencesRepositoryProtocol? = nil
    ) {
        self.recurringRepository = recurringRepository
        self.notificationService = notificationService
        self.preferencesRepository = preferencesRepository
    }

    @discardableResult
    public func execute(referenceDate: Date = Date()) async throws -> Int {
        // 1. Reconcile existing unsettled occurrences statuses based on user's local calendar
        try await recurringRepository.reconcilePendingOccurrencesStatuses(referenceDate: referenceDate)

        let schedules = try await recurringRepository.getAllRecurringTransactions()
        let activeSchedules = schedules.filter { $0.status == .active }
        let nowEpoch = Int64(referenceDate.timeIntervalSince1970 * 1000.0)

        // 2. Maintain a predictable occurrence horizon for the next 90 days
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = TimeZone.current
        let forwardHorizon = cal.date(byAdding: .day, value: 90, to: referenceDate) ?? referenceDate

        var newlyGeneratedCount = 0

        for schedule in activeSchedules {
            let timestamps = RecurrenceEngine.generateOccurrenceTimestamps(
                startDateEpoch: schedule.startDate,
                endDateEpoch: schedule.endDate,
                frequency: schedule.frequency,
                interval: schedule.recurrenceInterval,
                anchorDayOfMonth: schedule.dayOfMonth,
                anchorDayOfWeek: schedule.dayOfWeek,
                upTo: forwardHorizon
            )

            for ts in timestamps {
                let status = RecurrenceEngine.resolveStatus(
                    scheduledDateEpoch: ts,
                    isPaid: false,
                    isSkipped: false,
                    referenceDate: referenceDate
                )

                let occ = RecurringTransactionOccurrence(
                    recurringTransactionId: schedule.id,
                    scheduledDate: ts,
                    dueDate: ts,
                    amount: schedule.amount,
                    status: status
                )

                // Database unique index ensures duplicate occurrences are ignored
                if let occId = try await recurringRepository.insertOccurrenceIfNotExists(occ) {
                    newlyGeneratedCount += 1

                    // If schedule is explicitly configured for automatic ledger entry and is due now or in the past
                    if schedule.isAutoGenerated && ts <= nowEpoch {
                        _ = try await recurringRepository.markOccurrenceAsPaid(
                            occurrenceId: occId,
                            paymentMethod: schedule.paymentMethod,
                            paidAt: ts
                        )
                    }
                }
            }
        }

        // 3. Reconcile pending local notifications (prioritizing nearest 60 reminders)
        let currency = preferencesRepository?.getUserPreferences().currency ?? .usd
        let upcomingBills = try await recurringRepository.getUpcomingBills(limit: 60)
        await notificationService.reconcilePendingNotifications(occurrences: upcomingBills, currency: currency)

        return newlyGeneratedCount
    }
}
