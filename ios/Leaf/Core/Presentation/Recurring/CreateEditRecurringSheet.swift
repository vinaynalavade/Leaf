import SwiftUI

/// Creation and editing sheet for recurring expenses, income, subscriptions, and bill reminders.
public struct CreateEditRecurringSheet: View {
    @Environment(\.dismiss) private var dismiss
    @Environment(\.colorScheme) private var colorScheme

    public let existingSchedule: RecurringTransaction?
    public let categories: [Category]
    public let currency: Currency
    public let onSave: (
        _ id: Int64?,
        _ title: String,
        _ amount: Amount,
        _ type: TransactionType,
        _ categoryId: Int64,
        _ paymentMethod: PaymentMethod,
        _ note: String?,
        _ frequency: RecurringScheduleFrequency,
        _ interval: Int,
        _ dayOfMonth: Int,
        _ dayOfWeek: Int,
        _ startDate: Int64,
        _ endDate: Int64?,
        _ isAutoGenerated: Bool,
        _ reminderDaysBefore: Int?,
        _ isSubscription: Bool,
        _ editScope: RecurringScheduleEditScope
    ) async throws -> Void

    @State private var title: String = ""
    @State private var amountString: String = ""
    @State private var selectedType: TransactionType = .expense
    @State private var selectedCategoryId: Int64 = 0
    @State private var selectedPaymentMethod: PaymentMethod = .cash
    @State private var note: String = ""
    @State private var frequency: RecurringScheduleFrequency = .monthly
    @State private var recurrenceInterval: Int = 1
    @State private var dayOfMonth: Int = 1
    @State private var startDate: Date = Date()
    @State private var hasEndDate: Bool = false
    @State private var endDate: Date = Calendar.current.date(byAdding: .year, value: 1, to: Date()) ?? Date()
    @State private var isAutoGenerated: Bool = false
    @State private var reminderOptionIndex: Int = 1 // 0=None, 1=1 day before, 2=Same day, 3=3 days before, 4=1 week before
    @State private var isSubscription: Bool = false
    @State private var editScope: RecurringScheduleEditScope = .futureOnly

    @State private var isSaving: Bool = false
    @State private var errorMessage: String? = nil

    private let reminderOptions: [(label: String, days: Int?)] = [
        ("None", nil),
        ("1 Day Before", 1),
        ("On Due Date", 0),
        ("3 Days Before", 3),
        ("1 Week Before", 7)
    ]

    public init(
        existingSchedule: RecurringTransaction? = nil,
        categories: [Category],
        currency: Currency,
        onSave: @escaping (
            _ id: Int64?,
            _ title: String,
            _ amount: Amount,
            _ type: TransactionType,
            _ categoryId: Int64,
            _ paymentMethod: PaymentMethod,
            _ note: String?,
            _ frequency: RecurringScheduleFrequency,
            _ interval: Int,
            _ dayOfMonth: Int,
            _ dayOfWeek: Int,
            _ startDate: Int64,
            _ endDate: Int64?,
            _ isAutoGenerated: Bool,
            _ reminderDaysBefore: Int?,
            _ isSubscription: Bool,
            _ editScope: RecurringScheduleEditScope
        ) async throws -> Void
    ) {
        self.existingSchedule = existingSchedule
        self.categories = categories
        self.currency = currency
        self.onSave = onSave
    }

    private var filteredCategories: [Category] {
        categories.filter { $0.type == selectedType }
    }

    public var body: some View {
        NavigationStack {
            ZStack {
                LeafTheme.canvas(for: colorScheme).ignoresSafeArea()

                ScrollView {
                    VStack(spacing: 20) {
                        // 1. Transaction Type Segment
                        Picker("Type", selection: $selectedType) {
                            Text("Expense").tag(TransactionType.expense)
                            Text("Income").tag(TransactionType.income)
                        }
                        .pickerStyle(.segmented)
                        .padding(.horizontal)
                        .onChange(of: selectedType) { _, newType in
                            if let first = categories.first(where: { $0.type == newType }) {
                                selectedCategoryId = first.id
                            }
                        }

                        // 2. Core Details Card
                        VStack(alignment: .leading, spacing: 14) {
                            Text("BILL DETAILS")
                                .font(LeafTypography.captionBold)
                                .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                .padding(.horizontal, 4)

                            // Title Field
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Title")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                TextField("e.g. Netflix, Electricity Bill, Apartment Rent", text: $title)
                                    .font(LeafTypography.bodyMedium)
                                    .padding(12)
                                    .background(LeafTheme.card(for: colorScheme))
                                    .cornerRadius(10)
                                    .overlay(
                                        RoundedRectangle(cornerRadius: 10)
                                            .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                    )
                            }

                            // Amount Field
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Amount")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                HStack {
                                    Text(currency.symbol)
                                        .font(LeafTypography.headline)
                                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                    TextField("0.00", text: $amountString)
                                        .font(LeafTypography.headline)
                                        .keyboardType(.decimalPad)
                                }
                                .padding(12)
                                .background(LeafTheme.card(for: colorScheme))
                                .cornerRadius(10)
                                .overlay(
                                    RoundedRectangle(cornerRadius: 10)
                                        .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                )
                            }

                            // Category Picker
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Category")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                Picker("Category", selection: $selectedCategoryId) {
                                    ForEach(filteredCategories) { cat in
                                        Text(cat.name).tag(cat.id)
                                    }
                                }
                                .pickerStyle(.menu)
                                .padding(.horizontal, 12)
                                .padding(.vertical, 8)
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .background(LeafTheme.card(for: colorScheme))
                                .cornerRadius(10)
                                .overlay(
                                    RoundedRectangle(cornerRadius: 10)
                                        .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                )
                            }

                            // Payment Method
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Payment Method")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                Picker("Payment Method", selection: $selectedPaymentMethod) {
                                    ForEach(PaymentMethod.allCases) { method in
                                        Text(method.displayName).tag(method)
                                    }
                                }
                                .pickerStyle(.menu)
                                .padding(.horizontal, 12)
                                .padding(.vertical, 8)
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .background(LeafTheme.card(for: colorScheme))
                                .cornerRadius(10)
                                .overlay(
                                    RoundedRectangle(cornerRadius: 10)
                                        .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                )
                            }

                            // Subscription Flag
                            Toggle(isOn: $isSubscription) {
                                VStack(alignment: .leading, spacing: 2) {
                                    Text("Mark as Subscription")
                                        .font(LeafTypography.bodyMedium)
                                        .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))
                                    Text("Track under subscription analytics and monthly overhead")
                                        .font(LeafTypography.caption)
                                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                }
                            }
                            .tint(LeafTheme.purpleAccent)
                            .padding(.top, 4)
                        }
                        .padding(.horizontal)

                        // 3. Recurrence Schedule Card
                        VStack(alignment: .leading, spacing: 14) {
                            Text("RECURRENCE SCHEDULE")
                                .font(LeafTypography.captionBold)
                                .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                .padding(.horizontal, 4)

                            // Frequency
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Cadence")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                Picker("Frequency", selection: $frequency) {
                                    ForEach(RecurringScheduleFrequency.allCases) { freq in
                                        Text(freq.displayName).tag(freq)
                                    }
                                }
                                .pickerStyle(.menu)
                                .padding(.horizontal, 12)
                                .padding(.vertical, 8)
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .background(LeafTheme.card(for: colorScheme))
                                .cornerRadius(10)
                                .overlay(
                                    RoundedRectangle(cornerRadius: 10)
                                        .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                )
                            }

                            // Start Date
                            DatePicker(
                                "First Payment Date",
                                selection: $startDate,
                                displayedComponents: [.date]
                            )
                            .font(LeafTypography.bodyMedium)
                            .padding(12)
                            .background(LeafTheme.card(for: colorScheme))
                            .cornerRadius(10)
                            .overlay(
                                RoundedRectangle(cornerRadius: 10)
                                    .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                            )
                            .onChange(of: startDate) { _, newDate in
                                let day = Calendar.current.component(.day, from: newDate)
                                dayOfMonth = day
                            }

                            // End Date Toggle
                            Toggle(isOn: $hasEndDate) {
                                Text("Set End Date")
                                    .font(LeafTypography.bodyMedium)
                                    .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))
                            }
                            .tint(LeafTheme.brandEmerald)

                            if hasEndDate {
                                DatePicker(
                                    "Schedule End Date",
                                    selection: $endDate,
                                    in: startDate...,
                                    displayedComponents: [.date]
                                )
                                .font(LeafTypography.bodyMedium)
                                .padding(12)
                                .background(LeafTheme.card(for: colorScheme))
                                .cornerRadius(10)
                                .overlay(
                                    RoundedRectangle(cornerRadius: 10)
                                        .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                )
                            }
                        }
                        .padding(.horizontal)

                        // 4. Automation & Reminders Card
                        VStack(alignment: .leading, spacing: 14) {
                            Text("AUTOMATION & REMINDERS")
                                .font(LeafTypography.captionBold)
                                .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                .padding(.horizontal, 4)

                            // Auto-create transaction toggle
                            Toggle(isOn: $isAutoGenerated) {
                                VStack(alignment: .leading, spacing: 2) {
                                    Text("Auto-create transaction")
                                        .font(LeafTypography.bodyMedium)
                                        .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))
                                    Text("Automatically records a transaction in Leaf on the due date. Does not transfer money or withdraw from your bank account.")
                                        .font(LeafTypography.caption)
                                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                }
                            }
                            .tint(LeafTheme.brandEmerald)

                            // Reminder Preference
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Reminder Notification")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                Picker("Reminder", selection: $reminderOptionIndex) {
                                    ForEach(0..<reminderOptions.count, id: \.self) { idx in
                                        Text(reminderOptions[idx].label).tag(idx)
                                    }
                                }
                                .pickerStyle(.menu)
                                .padding(.horizontal, 12)
                                .padding(.vertical, 8)
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .background(LeafTheme.card(for: colorScheme))
                                .cornerRadius(10)
                                .overlay(
                                    RoundedRectangle(cornerRadius: 10)
                                        .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                )
                            }

                            // Optional Note
                            VStack(alignment: .leading, spacing: 6) {
                                Text("Notes (Optional)")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                                TextField("Account number, reference ID, cancellation policy", text: $note)
                                    .font(LeafTypography.bodyMedium)
                                    .padding(12)
                                    .background(LeafTheme.card(for: colorScheme))
                                    .cornerRadius(10)
                                    .overlay(
                                        RoundedRectangle(cornerRadius: 10)
                                            .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                                    )
                            }
                        }
                        .padding(.horizontal)

                        // 5. Scope of Changes (Only visible when editing an existing schedule)
                        if existingSchedule != nil {
                            VStack(alignment: .leading, spacing: 10) {
                                Text("SCOPE OF CHANGES")
                                    .font(LeafTypography.captionBold)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                    .padding(.horizontal, 4)

                                Picker("Scope", selection: $editScope) {
                                    ForEach(RecurringScheduleEditScope.allCases) { scope in
                                        Text(scope.title).tag(scope)
                                    }
                                }
                                .pickerStyle(.segmented)

                                Text(editScope.description)
                                    .font(LeafTypography.caption)
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                    .padding(.horizontal, 4)

                                HStack(spacing: 6) {
                                    Image(systemName: "checkmark.shield.fill")
                                        .font(.system(size: 12))
                                        .foregroundStyle(LeafTheme.brandEmerald)
                                    Text("Historical paid transactions are preserved and will not be rewritten.")
                                        .font(.system(size: 11, weight: .medium))
                                        .foregroundStyle(LeafTheme.brandEmerald)
                                }
                                .padding(.horizontal, 4)
                            }
                            .padding(.horizontal)
                        }

                        if let error = errorMessage {
                            Text(error)
                                .font(LeafTypography.captionBold)
                                .foregroundStyle(LeafTheme.expenseCoral)
                                .padding(.horizontal)
                        }

                        Spacer(minLength: 32)
                    }
                    .padding(.top, 16)
                }
            }
            .navigationTitle(existingSchedule == nil ? "New Recurring Schedule" : "Edit Schedule")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel") {
                        dismiss()
                    }
                    .foregroundStyle(LeafTheme.accent(for: colorScheme))
                }

                ToolbarItem(placement: .confirmationAction) {
                    Button("Save") {
                        save()
                    }
                    .font(LeafTypography.captionBold)
                    .foregroundStyle(LeafTheme.brandEmerald)
                    .disabled(isSaving || title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty)
                }
            }
            .onAppear {
                setupInitialValues()
            }
        }
    }

    private func setupInitialValues() {
        if let existing = existingSchedule {
            title = existing.title
            amountString = existing.amount.toInputString(currency: currency)
            selectedType = existing.type
            selectedCategoryId = existing.categoryId
            selectedPaymentMethod = existing.paymentMethod
            note = existing.note ?? ""
            frequency = existing.frequency
            recurrenceInterval = existing.recurrenceInterval
            dayOfMonth = existing.dayOfMonth
            startDate = Date(timeIntervalSince1970: Double(existing.startDate) / 1000.0)
            if let end = existing.endDate {
                hasEndDate = true
                endDate = Date(timeIntervalSince1970: Double(end) / 1000.0)
            } else {
                hasEndDate = false
            }
            isAutoGenerated = existing.isAutoGenerated
            isSubscription = existing.isSubscription

            if let days = existing.reminderDaysBefore {
                if let idx = reminderOptions.firstIndex(where: { $0.days == days }) {
                    reminderOptionIndex = idx
                }
            } else {
                reminderOptionIndex = 0
            }
        } else {
            if let first = filteredCategories.first {
                selectedCategoryId = first.id
            }
            dayOfMonth = Calendar.current.component(.day, from: startDate)
        }
    }

    private func save() {
        let cleanTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanTitle.isEmpty else {
            errorMessage = "Please enter a schedule title."
            return
        }

        guard let parsedAmount = Amount.fromStringOrNull(amountString, currency: currency), parsedAmount.isPositive else {
            errorMessage = "Please enter a valid amount greater than zero."
            return
        }

        guard selectedCategoryId > 0 else {
            errorMessage = "Please select a category."
            return
        }

        isSaving = true
        errorMessage = nil

        let startEpoch = Int64(startDate.timeIntervalSince1970 * 1000)
        let endEpoch = hasEndDate ? Int64(endDate.timeIntervalSince1970 * 1000) : nil
        let reminderDays = reminderOptions[reminderOptionIndex].days
        let cleanNote = note.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : note.trimmingCharacters(in: .whitespacesAndNewlines)

        let cal = Calendar.current
        let anchorDay = cal.component(.day, from: startDate)
        let anchorWeek = cal.component(.weekday, from: startDate)

        Task {
            do {
                try await onSave(
                    existingSchedule?.id,
                    cleanTitle,
                    parsedAmount,
                    selectedType,
                    selectedCategoryId,
                    selectedPaymentMethod,
                    cleanNote,
                    frequency,
                    recurrenceInterval,
                    anchorDay,
                    anchorWeek,
                    startEpoch,
                    endEpoch,
                    isAutoGenerated,
                    reminderDays,
                    isSubscription,
                    editScope
                )
                dismiss()
            } catch {
                errorMessage = error.localizedDescription
                isSaving = false
            }
        }
    }
}

