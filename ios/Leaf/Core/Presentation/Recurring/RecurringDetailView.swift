import SwiftUI

/// Detailed management screen for an individual recurring schedule, displaying its status,
/// next occurrence, projections, and full occurrence payment history.
public struct RecurringDetailView: View {
    @Environment(AppContainer.self) private var container
    @Environment(\.colorScheme) private var colorScheme
    @Environment(\.dismiss) private var dismiss

    public let scheduleId: Int64

    @State private var schedule: RecurringTransaction?
    @State private var occurrences: [RecurringTransactionOccurrence] = []
    @State private var categories: [Category] = []
    @State private var isEditSheetPresented: Bool = false
    @State private var isDeleteAlertPresented: Bool = false
    @State private var isCancelAlertPresented: Bool = false
    @State private var selectedOccurrenceForSnooze: RecurringTransactionOccurrence?
    @State private var occurrenceToReverse: RecurringTransactionOccurrence?
    @State private var isReverseAlertPresented: Bool = false

    public init(scheduleId: Int64) {
        self.scheduleId = scheduleId
    }

    private static let occurrenceDateFormatter: DateFormatter = {
        let f = DateFormatter()
        f.dateStyle = .medium
        return f
    }()

    private var currentCurrency: Currency {
        container.preferencesRepository.getUserPreferences().currency
    }

    public var body: some View {
        ZStack {
            LeafTheme.canvas(for: colorScheme).ignoresSafeArea()

            if let item = schedule {
                ScrollView {
                    VStack(spacing: 20) {
                        // 1. Hero Card
                        headerHeroCard(item)

                        // 2. Projection & Metrics Row
                        projectionsRow(item)

                        // 3. Management Actions
                        managementActionsSection(item)

                        // 4. Occurrences & Payment History
                        occurrencesHistorySection()

                        Spacer(minLength: 32)
                    }
                    .padding(.top, 16)
                }
                .refreshable {
                    await loadData()
                }
            } else {
                ProgressView()
                    .tint(LeafTheme.brandEmerald)
            }
        }
        .navigationTitle(schedule?.title ?? "Recurring Schedule")
        .navigationBarTitleDisplayMode(.inline)
        .toolbar {
            ToolbarItem(placement: .primaryAction) {
                Button("Edit") {
                    isEditSheetPresented = true
                }
                .font(LeafTypography.captionBold)
                .foregroundStyle(LeafTheme.brandEmerald)
            }
        }
        .task {
            await loadData()
        }
        .sheet(isPresented: $isEditSheetPresented) {
            if let item = schedule {
                CreateEditRecurringSheet(
                    existingSchedule: item,
                    categories: categories,
                    currency: currentCurrency,
                    onSave: { id, title, amount, type, catId, method, note, freq, interval, dayMonth, dayWeek, start, end, auto, reminder, isSub, scope in
                        let updated = RecurringTransaction(
                            id: item.id,
                            title: title,
                            amount: amount,
                            type: type,
                            categoryId: catId,
                            paymentMethod: method,
                            note: note,
                            frequency: freq,
                            recurrenceInterval: interval,
                            dayOfMonth: dayMonth,
                            dayOfWeek: dayWeek,
                            startDate: start,
                            endDate: end,
                            status: item.status,
                            isAutoGenerated: auto,
                            reminderDaysBefore: reminder,
                            isSubscription: isSub,
                            lastGeneratedDate: item.lastGeneratedDate,
                            nextOccurrenceDate: item.nextOccurrenceDate,
                            createdAt: item.createdAt,
                            updatedAt: Int64(Date().timeIntervalSince1970 * 1000)
                        )
                        try await container.updateRecurringTransactionUseCase.execute(updated, editScope: scope)
                        try? await container.generateDueOccurrencesUseCase.execute()
                        await loadData()
                    }
                )
            }
        }
        .sheet(item: $selectedOccurrenceForSnooze) { occ in
            SnoozeReminderSheet(occurrenceTitle: occ.title) { days in
                Task {
                    try? await container.snoozeBillReminderUseCase.execute(occurrenceId: occ.id, snoozeDays: days)
                    await loadData()
                }
            }
        }
        .alert("Delete Recurring Schedule?", isPresented: $isDeleteAlertPresented) {
            Button("Delete", role: .destructive) {
                Task {
                    try? await container.deleteRecurringTransactionUseCase.execute(id: scheduleId)
                    dismiss()
                }
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("This will delete the schedule and its scheduled bill occurrences. Previously generated financial transactions in your ledger will not be deleted.")
        }
        .alert("Cancel Schedule?", isPresented: $isCancelAlertPresented) {
            Button("Cancel Schedule", role: .destructive) {
                Task {
                    try? await container.cancelRecurringTransactionUseCase.execute(id: scheduleId)
                    await loadData()
                }
            }
            Button("Dismiss", role: .cancel) {}
        } message: {
            Text("No further occurrences will be generated. You can view payment history anytime.")
        }
        .alert("Reverse Payment?", isPresented: $isReverseAlertPresented) {
            Button("Reverse Payment", role: .destructive) {
                if let occ = occurrenceToReverse {
                    Task {
                        try? await container.reversePaidOccurrenceUseCase.execute(occurrenceId: occ.id)
                        await loadData()
                    }
                }
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            if let txId = occurrenceToReverse?.transactionId {
                Text("This will delete ledger transaction #\(txId) and restore this bill to unpaid status so it can be paid or edited again.")
            } else {
                Text("This will restore this occurrence to unpaid status.")
            }
        }
    }

    private func loadData() async {
        if let s = try? await container.getRecurringTransactionsUseCase.getById(id: scheduleId) {
            self.schedule = s
        }
        if let occs = try? await container.recurringRepository.getOccurrences(forRecurringId: scheduleId) {
            self.occurrences = occs
        }
        if let cats = try? await container.categoryRepository.getAllCategories() {
            self.categories = cats
        }
    }

    // MARK: - Subviews

    @ViewBuilder
    private func headerHeroCard(_ item: RecurringTransaction) -> some View {
        SquircleCard(cornerRadius: 20) {
            VStack(spacing: 16) {
                HStack(spacing: 14) {
                    CategoryIconBadge(
                        iconName: item.category?.iconName ?? "arrow.triangle.2.circlepath",
                        colorHex: item.category?.colorHex ?? "#10B981",
                        size: 48
                    )

                    VStack(alignment: .leading, spacing: 3) {
                        HStack(spacing: 6) {
                            Text(item.title)
                                .font(LeafTypography.titleMedium)
                                .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))

                            if item.isSubscription {
                                Text("SUBSCRIPTION")
                                    .font(.system(size: 9, weight: .bold))
                                    .foregroundStyle(LeafTheme.purpleAccent)
                                    .padding(.horizontal, 6)
                                    .padding(.vertical, 2)
                                    .background(LeafTheme.purpleAccent.opacity(0.12))
                                    .cornerRadius(6)
                            }
                        }

                        Text("\(item.frequency.displayName) • \(item.category?.name ?? "General")")
                            .font(LeafTypography.caption)
                            .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                    }

                    Spacer()

                    Text(item.status.displayName)
                        .font(.system(size: 11, weight: .bold))
                        .foregroundStyle(item.status == .active ? LeafTheme.brandEmerald : LeafTheme.warningGold)
                        .padding(.horizontal, 8)
                        .padding(.vertical, 4)
                        .background((item.status == .active ? LeafTheme.brandEmerald : LeafTheme.warningGold).opacity(0.12))
                        .cornerRadius(8)
                }

                Divider()

                HStack {
                    VStack(alignment: .leading, spacing: 2) {
                        Text("SCHEDULED AMOUNT")
                            .font(LeafTypography.captionBold)
                            .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                        Text(item.amount.formatted(currency: currentCurrency))
                            .font(LeafTypography.titleLarge)
                            .foregroundStyle(item.type == .expense ? LeafTheme.textPrimary(for: colorScheme) : LeafTheme.brandEmerald)
                    }

                    Spacer()

                    VStack(alignment: .trailing, spacing: 2) {
                        Text("NEXT PAYMENT")
                            .font(LeafTypography.captionBold)
                            .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                        if let next = item.nextOccurrenceDate {
                            let date = Date(timeIntervalSince1970: Double(next) / 1000.0)
                            Text(date, style: .date)
                                .font(LeafTypography.bodyBold)
                                .foregroundStyle(LeafTheme.brandEmerald)
                        } else {
                            Text("None scheduled")
                                .font(LeafTypography.bodyMedium)
                                .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                        }
                    }
                }
            }
            .padding(18)
        }
        .padding(.horizontal)
    }

    @ViewBuilder
    private func projectionsRow(_ item: RecurringTransaction) -> some View {
        HStack(spacing: 12) {
            SquircleCard(cornerRadius: 14) {
                VStack(alignment: .leading, spacing: 4) {
                    Text("ESTIMATED MONTHLY")
                        .font(LeafTypography.captionBold)
                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                    Text(item.estimatedMonthlyAmount.formatted(currency: currentCurrency))
                        .font(LeafTypography.headline)
                        .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))
                }
                .padding(14)
                .frame(maxWidth: .infinity, alignment: .leading)
            }

            SquircleCard(cornerRadius: 14) {
                VStack(alignment: .leading, spacing: 4) {
                    Text("ESTIMATED ANNUAL")
                        .font(LeafTypography.captionBold)
                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                    Text(item.estimatedAnnualAmount.formatted(currency: currentCurrency))
                        .font(LeafTypography.headline)
                        .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))
                }
                .padding(14)
                .frame(maxWidth: .infinity, alignment: .leading)
            }
        }
        .padding(.horizontal)
    }

    @ViewBuilder
    private func managementActionsSection(_ item: RecurringTransaction) -> some View {
        VStack(spacing: 10) {
            HStack(spacing: 10) {
                // Pause / Resume Button
                if item.status == .active {
                    Button {
                        Task {
                            try? await container.pauseRecurringTransactionUseCase.execute(id: item.id)
                            await loadData()
                        }
                    } label: {
                        HStack(spacing: 6) {
                            Image(systemName: "pause.fill")
                            Text("Pause Schedule")
                        }
                        .font(LeafTypography.captionBold)
                        .frame(maxWidth: .infinity)
                        .frame(height: 42)
                        .background(LeafTheme.card(for: colorScheme))
                        .foregroundStyle(LeafTheme.warningGold)
                        .cornerRadius(10)
                        .overlay(
                            RoundedRectangle(cornerRadius: 10)
                                .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                        )
                    }
                    .buttonStyle(.plain)
                } else if item.status == .paused {
                    Button {
                        Task {
                            try? await container.resumeRecurringTransactionUseCase.execute(id: item.id)
                            await loadData()
                        }
                    } label: {
                        HStack(spacing: 6) {
                            Image(systemName: "play.fill")
                            Text("Resume Schedule")
                        }
                        .font(LeafTypography.captionBold)
                        .frame(maxWidth: .infinity)
                        .frame(height: 42)
                        .background(LeafTheme.brandEmerald)
                        .foregroundStyle(Color.white)
                        .cornerRadius(10)
                    }
                    .buttonStyle(.plain)
                }

                // Cancel Button
                if item.status != .cancelled {
                    Button {
                        isCancelAlertPresented = true
                    } label: {
                        HStack(spacing: 6) {
                            Image(systemName: "xmark.circle")
                            Text("Cancel")
                        }
                        .font(LeafTypography.captionBold)
                        .frame(maxWidth: .infinity)
                        .frame(height: 42)
                        .background(LeafTheme.card(for: colorScheme))
                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                        .cornerRadius(10)
                        .overlay(
                            RoundedRectangle(cornerRadius: 10)
                                .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                        )
                    }
                    .buttonStyle(.plain)
                }

                // Delete Button
                Button {
                    isDeleteAlertPresented = true
                } label: {
                    Image(systemName: "trash")
                        .font(.system(size: 15))
                        .frame(width: 42, height: 42)
                        .background(LeafTheme.card(for: colorScheme))
                        .foregroundStyle(LeafTheme.expenseCoral)
                        .cornerRadius(10)
                        .overlay(
                            RoundedRectangle(cornerRadius: 10)
                                .stroke(LeafTheme.border(for: colorScheme), lineWidth: 1)
                        )
                }
                .buttonStyle(.plain)
            }
        }
        .padding(.horizontal)
    }

    @ViewBuilder
    private func occurrencesHistorySection() -> some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack {
                Text("OCCURRENCE HISTORY")
                    .font(LeafTypography.captionBold)
                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))

                Spacer()

                Text("\(occurrences.count) recorded")
                    .font(LeafTypography.caption)
                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
            }
            .padding(.horizontal)

            if occurrences.isEmpty {
                SquircleCard(cornerRadius: 14) {
                    Text("No payment occurrences generated yet.")
                        .font(LeafTypography.caption)
                        .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                        .padding(20)
                        .frame(maxWidth: .infinity)
                }
                .padding(.horizontal)
            } else {
                VStack(spacing: 8) {
                    ForEach(occurrences) { occ in
                        occurrenceRow(occ)
                    }
                }
                .padding(.horizontal)
            }
        }
    }

    @ViewBuilder
    private func occurrenceRow(_ occ: RecurringTransactionOccurrence) -> some View {
        let date = Date(timeIntervalSince1970: Double(occ.scheduledDate) / 1000.0)

        SquircleCard(cornerRadius: 12) {
            HStack(spacing: 12) {
                VStack(alignment: .leading, spacing: 3) {
                    HStack(spacing: 6) {
                        Text(date, style: .date)
                            .font(LeafTypography.bodyBold)
                            .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))

                        if occ.status == .paid {
                            Text("PAID")
                                .font(.system(size: 9, weight: .bold))
                                .foregroundStyle(LeafTheme.brandEmerald)
                                .padding(.horizontal, 6)
                                .padding(.vertical, 2)
                                .background(LeafTheme.brandEmerald.opacity(0.12))
                                .cornerRadius(4)
                        } else if occ.status == .skipped {
                            Text("SKIPPED")
                                .font(.system(size: 9, weight: .bold))
                                .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                .padding(.horizontal, 6)
                                .padding(.vertical, 2)
                                .background(LeafTheme.textSecondary(for: colorScheme).opacity(0.12))
                                .cornerRadius(4)
                        } else if occ.status == .overdue {
                            Text("OVERDUE")
                                .font(.system(size: 9, weight: .bold))
                                .foregroundStyle(LeafTheme.expenseCoral)
                                .padding(.horizontal, 6)
                                .padding(.vertical, 2)
                                .background(LeafTheme.expenseCoral.opacity(0.12))
                                .cornerRadius(4)
                        } else if occ.status == .due {
                            Text("DUE TODAY")
                                .font(.system(size: 9, weight: .bold))
                                .foregroundStyle(LeafTheme.warningGold)
                                .padding(.horizontal, 6)
                                .padding(.vertical, 2)
                                .background(LeafTheme.warningGold.opacity(0.12))
                                .cornerRadius(4)
                        }
                    }

                    if let paidAt = occ.paidAt {
                        let paidDate = Date(timeIntervalSince1970: Double(paidAt) / 1000.0)
                        Text("Paid: \(Self.occurrenceDateFormatter.string(from: paidDate)) • Tx #\(occ.transactionId ?? 0)")
                            .font(LeafTypography.caption)
                            .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                    } else if let snoozed = occ.snoozedUntil {
                        let snoozeDate = Date(timeIntervalSince1970: Double(snoozed) / 1000.0)
                        Text("Reminder snoozed to \(Self.occurrenceDateFormatter.string(from: snoozeDate))")
                            .font(LeafTypography.caption)
                            .foregroundStyle(LeafTheme.warningGold)
                    } else if occ.status == .skipped {
                        Text("Skipped — no expense recorded")
                            .font(LeafTypography.caption)
                            .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                    } else {
                        Text("Due date: \(Self.occurrenceDateFormatter.string(from: date))")
                            .font(LeafTypography.caption)
                            .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                    }
                }

                Spacer()

                VStack(alignment: .trailing, spacing: 4) {
                    Text(occ.amount.formatted(currency: currentCurrency))
                        .font(LeafTypography.bodyBold)
                        .foregroundStyle(LeafTheme.textPrimary(for: colorScheme))

                    if occ.status.isUnsettled {
                        HStack(spacing: 6) {
                            Button("Pay") {
                                Task {
                                    try? await container.markBillAsPaidUseCase.execute(occurrenceId: occ.id)
                                    await loadData()
                                }
                            }
                            .font(LeafTypography.captionBold)
                            .padding(.horizontal, 10)
                            .padding(.vertical, 4)
                            .background(LeafTheme.brandEmerald)
                            .foregroundStyle(Color.white)
                            .cornerRadius(6)

                            Menu {
                                Button("Snooze Reminder") {
                                    selectedOccurrenceForSnooze = occ
                                }
                                Button("Skip This Bill") {
                                    Task {
                                        try? await container.skipBillOccurrenceUseCase.execute(occurrenceId: occ.id)
                                        await loadData()
                                    }
                                }
                            } label: {
                                Image(systemName: "ellipsis.circle")
                                    .font(.system(size: 16))
                                    .foregroundStyle(LeafTheme.textSecondary(for: colorScheme))
                                    .padding(4)
                            }
                        }
                    } else if occ.status == .paid {
                        Button("Reverse") {
                            occurrenceToReverse = occ
                            isReverseAlertPresented = true
                        }
                        .font(.system(size: 11, weight: .semibold))
                        .foregroundStyle(LeafTheme.expenseCoral)
                        .padding(.horizontal, 8)
                        .padding(.vertical, 3)
                        .background(LeafTheme.expenseCoral.opacity(0.10))
                        .cornerRadius(6)
                    }
                }
            }
            .padding(12)
        }
    }
}

